"""Collision-aware IK with nonlinear acceptance checks for the new skeleton.

The linear collision limit shapes each QP step. A separate geometry check then
backtracks the integrated candidate so that accepted poses retain clearance.
The original core, MJCF, and its four knee equality definitions stay unchanged.
"""

from __future__ import annotations

import itertools

import mink
import mujoco as mj
import numpy as np

from skeleton_retarget.retargeting.motion_retarget import (
    GeneralMotionRetargeting as BaseMotionRetargeting,
)

GEOM_NAME_PAIRS = tuple(
    (f"{left}_l_collision", f"{right}_r_collision")
    for left, right in itertools.product(("thigh", "shin", "foot"), repeat=2)
)
GEOM_PAIRS = tuple(([left], [right]) for left, right in GEOM_NAME_PAIRS)
LOCKED_NAMES = tuple(f"knee_{axis}_{side}" for side in "rl" for axis in "xz")


def collision_distances(model, qpos, data=None, *, distance_cap=1.0):
    """Return all nine cross-leg signed distances, capped at distance_cap.

    These explicit geometry queries include separated pairs; they do not rely
    on the contact margin or on contacts generated by MuJoCo's broad phase.
    ``data`` is optional scratch storage and is overwritten by this function.
    """
    if data is None:
        data = mj.MjData(model)
    qpos = np.asarray(qpos, dtype=float)
    if qpos.shape != (model.nq,) or not np.isfinite(qpos).all():
        raise ValueError("Expected one finite model qpos vector")
    data.qpos[:] = qpos
    mj.mj_forward(model, data)
    return {
        (left, right): float(
            mj.mj_geomDistance(
                model,
                data,
                model.geom(left).id,
                model.geom(right).id,
                distance_cap,
                None,
            )
        )
        for left, right in GEOM_NAME_PAIRS
    }


def minimum_clearance(model, qpos, data=None, *, distance_cap=1.0):
    """Return the minimum actual cross-leg geometry distance in meters."""
    return min(
        collision_distances(model, qpos, data, distance_cap=distance_cap).values()
    )


class CollisionAwareMotionRetargeting(BaseMotionRetargeting):
    """Preserve the two IK stages while accepting only safe integrated steps."""

    def __init__(
        self,
        robot_xml_path,
        ik_config_path,
        actual_human_height=None,
        solver="daqp",
        damping=0.5,
        verbose=True,
        use_velocity_limit=False,
        use_equality_constraints=True,
        *,
        safety_clearance=0.001,
        qp_clearance=0.005,
        collision_detection_distance=0.08,
        approach_fraction=0.5,
        max_backtracks=20,
    ):
        if not use_equality_constraints:
            raise ValueError("Collision skeleton IK requires its four knee equalities")
        if not 0 <= safety_clearance < qp_clearance < collision_detection_distance:
            raise ValueError(
                "Require 0 <= safety clearance < QP clearance < detection distance"
            )
        if not 0 < approach_fraction <= 1 or max_backtracks < 0:
            raise ValueError("Invalid approach fraction or backtracking count")
        super().__init__(
            robot_xml_path=robot_xml_path,
            ik_config_path=ik_config_path,
            actual_human_height=actual_human_height,
            solver=solver,
            damping=damping,
            verbose=verbose,
            use_velocity_limit=use_velocity_limit,
            use_equality_constraints=True,
        )
        self.safety_clearance = float(safety_clearance)
        self.qp_clearance = float(qp_clearance)
        self.max_backtracks = int(max_backtracks)
        self._collision_data = mj.MjData(self.model)
        self._locked_qpos = np.array(
            [int(self.model.joint(name).qposadr[0]) for name in LOCKED_NAMES]
        )
        self._limited_joints = np.flatnonzero(self.model.jnt_limited)
        if np.any(
            self.model.jnt_type[self._limited_joints] != int(mj.mjtJoint.mjJNT_HINGE)
        ):
            raise ValueError(
                "This independent skeleton adapter expects hinge joint limits"
            )
        self._limited_qpos = self.model.jnt_qposadr[self._limited_joints]
        self._ranges = self.model.jnt_range[self._limited_joints]
        dt = float(self.model.opt.timestep)
        # Installed Mink builds a displacement QP but divides the collision
        # upper bound by dt. Compensate here so its bound is fraction*(d-d_min).
        self.collision_limit = mink.CollisionAvoidanceLimit(
            self.model,
            geom_pairs=GEOM_PAIRS,
            gain=approach_fraction * dt,
            minimum_distance_from_collisions=qp_clearance,
            collision_detection_distance=collision_detection_distance,
            bound_relaxation=0.0,
        )
        if len(self.collision_limit.geom_id_pairs) != 9:
            raise ValueError("Expected all nine cross-leg collision constraints")
        self.ik_limits.append(self.collision_limit)
        self._interpolation_anchor = None
        self.collision_statistics = {
            "proposed_steps": 0,
            "accepted_steps": 0,
            "rejected_steps": 0,
            "backtracked_steps": 0,
            "backtrack_halvings": 0,
            "minimum_accepted_alpha": 1.0,
            "minimum_accepted_clearance_m": None,
            "anchor_candidate_checks": 0,
            "anchor_sample_checks": 0,
            "anchor_rejected_candidates": 0,
            "minimum_accepted_anchor_clearance_m": None,
            "safety_clearance_m": self.safety_clearance,
            "qp_clearance_m": self.qp_clearance,
            "collision_detection_distance_m": float(collision_detection_distance),
            "approach_fraction": float(approach_fraction),
            "mink_gain_with_dt_compensation": float(approach_fraction * dt),
        }
        self._check_start()

    @property
    def interpolation_anchor(self):
        """Optional previous output pose used for interpolation safety checks."""
        if self._interpolation_anchor is None:
            return None
        return self._interpolation_anchor.copy()

    @interpolation_anchor.setter
    def interpolation_anchor(self, qpos):
        if qpos is None:
            self._interpolation_anchor = None
            return
        anchor = np.asarray(qpos, dtype=float).copy()
        if anchor.shape != (self.model.nq,) or not self._joint_coordinates_valid(
            anchor
        ):
            raise ValueError(
                "Interpolation anchor must satisfy model limits and knee locks"
            )
        if (
            minimum_clearance(self.model, anchor, self._collision_data)
            < self.safety_clearance
        ):
            raise ValueError(
                "Interpolation anchor must have the required geometry clearance"
            )
        self._interpolation_anchor = anchor

    def _anchor_segment_clearance(self, candidate):
        """Check three interior points of the anchor-to-candidate segment.

        This samples the MuJoCo configuration interpolation, including root
        quaternion integration. It is a discrete check, not a swept-volume proof.
        """
        anchor = self._interpolation_anchor
        if anchor is None:
            return None
        statistics = self.collision_statistics
        statistics["anchor_candidate_checks"] += 1
        delta = np.empty(self.model.nv)
        mj.mj_differentiatePos(self.model, delta, 1.0, anchor, candidate)
        minimum = float("inf")
        for fraction in (0.25, 0.5, 0.75):
            sample = anchor.copy()
            mj.mj_integratePos(self.model, sample, delta, fraction)
            statistics["anchor_sample_checks"] += 1
            if not self._joint_coordinates_valid(sample):
                statistics["anchor_rejected_candidates"] += 1
                return float("-inf")
            minimum = min(
                minimum, minimum_clearance(self.model, sample, self._collision_data)
            )
            if minimum < self.safety_clearance:
                statistics["anchor_rejected_candidates"] += 1
                return minimum
        return minimum

    def _joint_coordinates_valid(self, qpos):
        coordinates = qpos[self._limited_qpos]
        return (
            np.isfinite(qpos).all()
            and np.all(coordinates >= self._ranges[:, 0] - 1e-10)
            and np.all(coordinates <= self._ranges[:, 1] + 1e-10)
            and np.max(np.abs(qpos[self._locked_qpos])) <= 1e-10
        )

    def _check_start(self):
        qpos = self.configuration.data.qpos
        if not self._joint_coordinates_valid(qpos):
            raise ValueError(
                "Collision-aware IK must start inside joint limits with knees locked"
            )
        clearance = minimum_clearance(self.model, qpos, self._collision_data)
        if clearance < self.safety_clearance - 1e-10:
            raise ValueError(
                "Collision-aware IK requires a safe initial pose; "
                f"minimum clearance is {clearance:.6g} m"
            )

    def _integrate_safely(self, velocity, dt):
        """Accept a nonlinear geometry-safe fraction of one proposed QP step."""
        statistics = self.collision_statistics
        statistics["proposed_steps"] += 1
        initial = self.configuration.data.qpos.copy()
        for reductions in range(self.max_backtracks + 1):
            alpha = 0.5**reductions
            candidate = initial.copy()
            mj.mj_integratePos(self.model, candidate, velocity, dt * alpha)
            # The exact zero locks remove only numerical QP/integration noise.
            candidate[self._locked_qpos] = 0.0
            if self._joint_coordinates_valid(candidate):
                clearance = minimum_clearance(
                    self.model, candidate, self._collision_data
                )
                if clearance >= self.safety_clearance:
                    anchor_clearance = self._anchor_segment_clearance(candidate)
                    if (
                        anchor_clearance is not None
                        and anchor_clearance < self.safety_clearance
                    ):
                        continue
                    self.configuration.update(candidate)
                    statistics["accepted_steps"] += 1
                    statistics["backtrack_halvings"] += reductions
                    statistics["backtracked_steps"] += int(reductions > 0)
                    statistics["minimum_accepted_alpha"] = min(
                        statistics["minimum_accepted_alpha"], alpha
                    )
                    previous = statistics["minimum_accepted_clearance_m"]
                    statistics["minimum_accepted_clearance_m"] = (
                        clearance if previous is None else min(previous, clearance)
                    )
                    if anchor_clearance is not None:
                        previous = statistics["minimum_accepted_anchor_clearance_m"]
                        statistics["minimum_accepted_anchor_clearance_m"] = (
                            anchor_clearance
                            if previous is None
                            else min(previous, anchor_clearance)
                        )
                    return True
        statistics["rejected_steps"] += 1
        statistics["backtracked_steps"] += 1
        statistics["backtrack_halvings"] += self.max_backtracks
        return False

    def _solve_stage(self, tasks, error, max_iterations):
        if not tasks:
            return
        for _ in range(max_iterations):
            previous_error = error()
            dt = float(self.model.opt.timestep)
            velocity = mink.solve_ik(
                self.configuration,
                tasks,
                dt,
                self.solver,
                self.damping,
                limits=self.ik_limits,
                constraints=self.ik_constraints,
            )
            if not self._integrate_safely(velocity, dt):
                break
            if previous_error - error() <= 0.001:
                break

    def solve_tasks(self, tasks, max_iterations=20):
        """Fit arbitrary Mink tasks from the current safe configuration.

        This supports posture/root fitting after temporal interpolation while
        preserving the same geometry acceptance checks, knee locks and limits.
        A rejected step leaves the current configuration unchanged.
        """
        if not isinstance(max_iterations, int) or max_iterations < 0:
            raise ValueError("max_iterations must be a nonnegative integer")
        self._check_start()
        tasks = list(tasks)

        def error():
            return np.linalg.norm(
                np.concatenate(
                    [task.compute_error(self.configuration) for task in tasks]
                )
            )

        self._solve_stage(tasks, error, max_iterations)
        return self.configuration.data.qpos.copy()

    def retarget(self, human_data, offset_to_ground=False):
        self._check_start()
        self.update_targets(human_data, offset_to_ground)
        if self.use_ik_match_table1:
            self._solve_stage(self.tasks1, self.error1, self.max_iter + 1)
        if self.use_ik_match_table2:
            self._solve_stage(self.tasks2, self.error2, self.max_iter + 1)
        return self.configuration.data.qpos.copy()
